#!/usr/bin/env node
// Build stats.js — a static lookup of every NFL skill player's stats keyed
// by their ESPN athlete ID. The browser then fetches each team's CURRENT
// roster live from ESPN at page load, joins it against this lookup, and
// computes room status client-side. That way rosters are always live and
// stats can ride a separate update cadence.
//
// Usage: node scripts/build-analysis.mjs
//
// Re-run when nflverse publishes a new stats CSV (bump STATS_SEASON).

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

const STATS_SEASON   = 2024;
const ROSTER_SEASON  = 2025; // for the espn_id ↔ gsis_id bridge
const STATS_URL  = `https://github.com/nflverse/nflverse-data/releases/download/player_stats/stats_player_reg_${STATS_SEASON}.csv`;
const ROSTER_URL = `https://github.com/nflverse/nflverse-data/releases/download/rosters/roster_${ROSTER_SEASON}.csv`;

const log = (...a) => console.log('[build]', ...a);
const num = (v) => (v == null || v === '' ? 0 : Number(v));

function parseCSV(text) {
  const rows = [];
  let row = [], field = '', inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') inQuotes = false;
      else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c === '\r') { /* skip */ }
    else field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  const [header, ...data] = rows;
  return data
    .filter(r => r.length === header.length)
    .map(r => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

async function fetchText(url) {
  const r = await fetch(url, { redirect: 'follow' });
  if (!r.ok) throw new Error(`${r.status} ${r.statusText} for ${url}`);
  return r.text();
}

async function main() {
  log(`fetching nflverse stats (${STATS_SEASON})…`);
  const stats = parseCSV(await fetchText(STATS_URL));
  log(`  ${stats.length} player-season rows`);

  log(`fetching nflverse rosters (${ROSTER_SEASON}) for espn_id ↔ gsis_id bridge…`);
  const rosters = parseCSV(await fetchText(ROSTER_URL));
  // gsis_id → espn_id (first occurrence wins; same player has multiple weekly rows)
  const gsisToEspn = {};
  for (const r of rosters) {
    if (r.gsis_id && r.espn_id && !gsisToEspn[r.gsis_id]) {
      gsisToEspn[r.gsis_id] = r.espn_id;
    }
  }
  log(`  ${Object.keys(gsisToEspn).length} gsis→espn mappings`);

  // Build a lean stats record per player. Only the fields the bucketers need,
  // keyed by espn_id so the browser can join straight against ESPN's roster
  // response.
  const byEspnId = {};
  let mapped = 0;
  for (const r of stats) {
    const espn_id = gsisToEspn[r.player_id];
    if (!espn_id) continue;
    const pos = r.position_group;
    if (!['QB','RB','WR','TE'].includes(pos)) continue;
    byEspnId[espn_id] = {
      name: r.player_display_name,
      position: pos,
      games: num(r.games),
      // QB
      attempts: num(r.attempts),
      sacks_suffered: num(r.sacks_suffered),
      passing_epa: +num(r.passing_epa).toFixed(2),
      // RB
      carries: num(r.carries),
      // WR / TE
      targets: num(r.targets),
      target_share: +num(r.target_share).toFixed(3),
    };
    mapped++;
  }
  log(`  ${mapped} skill-position players written to stats.js`);

  const out = {
    generatedAt: new Date().toISOString().slice(0, 10),
    statsSeason: STATS_SEASON,
    rosterSeason: ROSTER_SEASON,
    source: `nflverse stats_player_reg_${STATS_SEASON} (rosters joined via roster_${ROSTER_SEASON} for espn_id bridge)`,
    byEspnId,
  };

  const file = resolve(ROOT, 'stats.js');
  await writeFile(file, `// Auto-generated by scripts/build-analysis.mjs — do not edit by hand.\nwindow.STATS = ${JSON.stringify(out, null, 2)};\n`);
  log(`wrote ${file}`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
